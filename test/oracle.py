#!/usr/bin/env python3
"""Vanilla oracle for the three locate branches (structure, biome, poi).

The golden battery checks LocateMore against a recorded file. This checks it
against unmodified vanilla itself: the same plain /locate commands at many
origins, once with LocateMore active and once with every mixin stepped aside
(lmlab bypass on). Vanilla's answer is the oracle; nothing here is ever
blessed from the mod's own output.

    python test/oracle.py gen > test/oracle-battery.txt
    BATTERY=test/oracle-battery.txt RAW_ONLY=1 sh test/run.sh
    python test/oracle.py check test/last-run.log          # stage 1
    python test/oracle.py gen2 test/last-run.log > test/oracle-battery2.txt
    BATTERY=test/oracle-battery2.txt RAW_ONLY=1 sh test/run.sh
    python test/oracle.py check2 test/last-run.log

Stage 1 verdicts per (command, origin):
  same          both answered with the same coordinates
  none          neither found anything
  mod_nearer    both answered, the mod's answer is strictly nearer (vanilla's
                raster order is not distance order, MC-138887); stage 2 asks
                vanilla from the mod's own position to prove the mod's hit is
                a real start/biome column/poi
  mod_beyond    vanilla found nothing within its radius, the mod found a hit
                farther than that radius
  VIOLATION     the mod found nothing vanilla found, answered farther than
                vanilla, or answered inside vanilla's radius where vanilla
                found nothing
Exit status is 1 when any violation exists.
"""
import math
import re
import sys

STRUCTURES = [
    "#minecraft:village", "minecraft:pillager_outpost", "minecraft:desert_pyramid",
    "minecraft:jungle_pyramid", "minecraft:igloo", "minecraft:swamp_hut",
    "minecraft:shipwreck", "#minecraft:ocean_ruin", "minecraft:monument",
    "#minecraft:ruined_portal", "minecraft:buried_treasure", "minecraft:stronghold",
    "minecraft:ancient_city", "minecraft:trail_ruins", "#minecraft:mineshaft",
    "minecraft:mansion",
]
NETHER_STRUCTURES = ["minecraft:fortress", "minecraft:bastion_remnant", "#minecraft:ruined_portal"]
END_STRUCTURES = ["minecraft:end_city"]
BIOMES = [
    "minecraft:plains", "minecraft:desert", "minecraft:river", "minecraft:forest",
    "#minecraft:is_ocean", "minecraft:jungle", "minecraft:badlands", "minecraft:savanna",
    "minecraft:taiga", "minecraft:swamp", "minecraft:snowy_plains", "minecraft:mushroom_fields",
    "minecraft:cherry_grove", "minecraft:dark_forest", "minecraft:lush_caves",
    "minecraft:dripstone_caves", "minecraft:deep_dark",
]
NETHER_BIOMES = ["minecraft:nether_wastes", "minecraft:soul_sand_valley", "minecraft:warped_forest",
                 "minecraft:crimson_forest", "minecraft:basalt_deltas"]
END_BIOMES = ["minecraft:end_highlands", "minecraft:small_end_islands"]
POIS = ["#minecraft:village", "minecraft:meeting_point", "#minecraft:acquirable_job_site", "minecraft:home"]

# Fixed origins (x, y, z): no randomness, so every run asks the same questions.
ORIGINS = [(0, 100, 0), (1531, 70, -2210), (-3047, 64, 1893), (2788, 80, 3412),
           (-1203, 120, -3561), (4150, 64, -490), (-4402, 90, -2750), (610, 64, 4890)]
POI_ORIGINS = [(0, 70, 0), (60, 70, -45), (-70, 75, 30), (25, 64, 80), (-40, 90, -85)]
# Vanilla's own limits, in blocks: structures 100 chunks of rings (1600),
# biomes 6400 horizontally, poi 256.
LIMIT = {"structure": 1600, "biome": 6400, "poi": 256}

COORD = re.compile(r"\[(-?\d+), (-?\d+|~), (-?\d+)\]")


def battery():
    lines = []
    queries = []
    for dim, structures, biomes in (
            ("minecraft:overworld", STRUCTURES, BIOMES),
            ("minecraft:the_nether", NETHER_STRUCTURES, NETHER_BIOMES),
            ("minecraft:the_end", END_STRUCTURES, END_BIOMES)):
        origins = ORIGINS if dim == "minecraft:overworld" else ORIGINS[:3]
        for ox, oy, oz in origins:
            if dim != "minecraft:overworld":
                oy = 64
            for s in structures:
                queries.append((dim, ox, oy, oz, "structure", s))
            for b in biomes:
                queries.append((dim, ox, oy, oz, "biome", b))
    for ox, oy, oz in POI_ORIGINS:
        for p in POIS:
            queries.append(("minecraft:overworld", ox, oy, oz, "poi", p))
    return queries


def command(q):
    dim, x, y, z, kind, ident = q
    return f"execute in {dim} positioned {x} {y} {z} run locate {kind} {ident}"


def gen():
    qs = battery()
    out = ["# oracle battery, stage 1 (generated by test/oracle.py)", "forceload add -96 -96 96 96",
           "lmlab pause 1800", "lmlab bypass off"]
    pois = [q for q in qs if q[4] == "poi"]
    rest = [q for q in qs if q[4] != "poi"]
    out += [command(q) for q in rest]
    out += [command(q) for q in pois]
    out.append("lmlab bypass on")
    out += [command(q) for q in rest]
    out += [command(q) for q in pois]
    out.append("lmlab bypass off")
    print("\n".join(out))


def parse(log_path):
    """Returns {(phase, command): (coords or None, raw lines, warnings)}."""
    results = {}
    seen = {}
    current = None
    bypass = False
    for raw in open(log_path, encoding="utf-8", errors="replace"):
        line = raw.rstrip("\n")
        m = re.search(r"\(locatemorelab\) BATTERY> (.*)$", line)
        if m:
            cmd = m.group(1)
            if cmd.startswith("lmlab bypass"):
                bypass = cmd.endswith("on")
                current = None
            elif cmd.startswith("execute"):
                key = ("vanilla" if bypass else "mod", cmd)
                seen[key] = seen.get(key, 0) + 1
                current = key
                results[key] = [None, [], []]
            else:
                current = None
            continue
        if current is None:
            continue
        if "[Server thread/INFO] (Minecraft)" in line:
            text = line.split("(Minecraft) ", 1)[1]
            results[current][1].append(text)
            c = COORD.search(text)
            if c and results[current][0] is None and not text.startswith("Searching"):
                results[current][0] = tuple(None if v == "~" else int(v) for v in c.groups())
        elif "/WARN]" in line or "/ERROR]" in line:
            results[current][2].append(line)
    return results


def split(cmd):
    m = re.match(r"execute in (\S+) positioned (-?\d+) (-?\d+) (-?\d+) run locate (\S+) (\S+)$", cmd)
    dim, x, y, z, kind, ident = m.groups()
    return dim, int(x), int(y), int(z), kind, ident


def dist(kind, o, p):
    # Horizontal for every kind: vanilla prints poi coordinates with a "~"
    # for y, so a 3D poi distance cannot be formed from its answer.
    dx, dz = p[0] - o[0], p[2] - o[2]
    return math.sqrt(dx * dx + dz * dz)


def classify(kind, origin, mod, van):
    if mod is None and van is None:
        return "none"
    if van is None:
        return "mod_beyond" if dist(kind, origin, mod) > LIMIT[kind] else "VIOLATION(mod answered inside vanilla's radius, vanilla found nothing)"
    if mod is None:
        return "VIOLATION(mod found nothing, vanilla found a hit)"
    if (mod[0], mod[2]) == (van[0], van[2]):
        return "same"
    dm, dv = dist(kind, origin, mod), dist(kind, origin, van)
    if dm < dv:
        return "mod_nearer"
    if dm == dv:
        return "same_distance_other_hit"
    return "VIOLATION(mod answered farther than vanilla)"


def check(log_path):
    res = parse(log_path)
    pairs = {}
    for (phase, cmd), val in res.items():
        pairs.setdefault(cmd, {})[phase] = val
    counts = {}
    rows = []
    warns = 0
    for cmd, d in pairs.items():
        if "mod" not in d or "vanilla" not in d:
            counts["INCOMPLETE"] = counts.get("INCOMPLETE", 0) + 1
            rows.append(("INCOMPLETE", cmd, d))
            continue
        dim, x, y, z, kind, ident = split(cmd)
        verdict = classify(kind, (x, y, z), d["mod"][0], d["vanilla"][0])
        key = (kind, verdict.split("(")[0])
        counts[key] = counts.get(key, 0) + 1
        warns += len(d["mod"][2])
        rows.append((verdict, cmd, d))
    for key in sorted(counts, key=str):
        print(f"{key}: {counts[key]}")
    bad = [r for r in rows if r[0].startswith(("VIOLATION", "INCOMPLETE"))]
    for v, cmd, d in bad:
        print("---", v, cmd)
        for phase in ("mod", "vanilla"):
            if phase in d:
                print("   ", phase, d[phase][0], d[phase][1][:2], d[phase][2][:2])
    print(f"{len(rows)} pairs, {len(bad)} violations/incomplete, {warns} mod WARN/ERROR lines")
    near = [r for r in rows if r[0] in ("mod_nearer", "same_distance_other_hit")]
    open("test/oracle-stage2.json", "w").write(__import__("json").dumps(
        [[v, cmd, d["mod"][0]] for v, cmd, d in near]))
    for v, cmd, d in near:
        print("  ", v, cmd, "mod", d["mod"][0], "vanilla", d["vanilla"][0])
    return 1 if bad else 0


def gen2():
    import json
    near = json.load(open("test/oracle-stage2.json"))
    out = ["# oracle battery, stage 2: vanilla asked from the mod's own answer", "lmlab bypass on"]
    for v, cmd, mod in near:
        dim, x, y, z, kind, ident = split(cmd)
        yy = mod[1] if mod[1] is not None else y
        out.append(f"execute in {dim} positioned {mod[0]} {yy} {mod[2]} run locate {kind} {ident}")
    out.append("lmlab bypass off")
    print("\n".join(out))


def check2(log_path):
    import json
    near = json.load(open("test/oracle-stage2.json"))
    res = parse(log_path)
    bad = 0
    for v, cmd, mod in near:
        dim, x, y, z, kind, ident = split(cmd)
        yy = mod[1] if mod[1] is not None else y
        c2 = f"execute in {dim} positioned {mod[0]} {yy} {mod[2]} run locate {kind} {ident}"
        got = res.get(("vanilla", c2), [None])[0]
        ok = got is not None and (got[0], got[2]) == (mod[0], mod[2])
        print("OK " if ok else "BAD", cmd, "mod", mod, "vanilla-at-mod", got)
        bad += 0 if ok else 1
    print(f"{len(near)} mod-nearer hits re-asked of vanilla, {bad} not confirmed")
    return 1 if bad else 0


if __name__ == "__main__":
    mode = sys.argv[1]
    if mode == "gen":
        gen()
    elif mode == "gen2":
        gen2()
    elif mode == "check":
        sys.exit(check(sys.argv[2]))
    elif mode == "check2":
        sys.exit(check2(sys.argv[2]))
    else:
        sys.exit(__doc__)
